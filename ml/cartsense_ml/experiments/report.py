"""Render the model comparison table from result JSON files.

The Markdown is generated from ``reports/results/<stage>/*.json`` only, so the
published numbers are exactly what the evaluation scripts produced.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

METRICS = ("precision", "recall", "ndcg", "map", "hit_rate", "coverage")
HEADERS = {"precision": "P", "recall": "R", "ndcg": "NDCG", "map": "MAP", "hit_rate": "HR", "coverage": "Cov"}


def load_results(results_dir: Path) -> list[dict[str, Any]]:
    results = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(results_dir.glob("*.json"))]
    # Best NDCG at the smallest cutoff first
    return sorted(results, key=lambda r: -r["overall"][_first_ndcg_key(r)])


def _first_ndcg_key(result: dict[str, Any]) -> str:
    ks = sorted(int(k.split("@")[1]) for k in result["overall"] if k.startswith("ndcg@"))
    return f"ndcg@{ks[0]}"


def _fmt(value: float) -> str:
    return f"{value:.4f}"


def render_table(results: list[dict[str, Any]], k_values: list[int]) -> str:
    if not results:
        return "_No results yet._\n"
    stage = results[0]["stage"]
    first = results[0]
    lines = [
        f"# Offline evaluation: {stage}",
        "",
        "_Generated by `python -m cartsense_ml.experiments.run`. Do not edit by hand._",
        "",
        f"Users evaluated: {first['n_users']:,} ({first['n_warm_users']:,} with history, "
        f"{first['n_cold_users']:,} without). Recommendable items at the cutoff: "
        f"{first['n_recommendable_items']:,}.",
        "",
        "Oracle recall (best possible, given products released after the cutoff cannot be "
        "recommended): " + ", ".join(f"{k} = {_fmt(v)}" for k, v in first["oracle_recall"].items()) + ".",
    ]
    for k in k_values:
        cols = [f"{HEADERS[m]}@{k}" for m in METRICS]
        lines += ["", f"## All users, K = {k}", "",
                  "| Model | " + " | ".join(cols) + " |",
                  "|---|" + "---:|" * len(cols)]
        for r in results:
            vals = [_fmt(r["overall"][f"{m}@{k}"]) for m in METRICS]
            lines.append(f"| {r['label']} | " + " | ".join(vals) + " |")

    k = k_values[0]
    lines += ["", f"## By user segment, K = {k}", "",
              f"| Model | NDCG@{k} warm | R@{k} warm | NDCG@{k} cold | R@{k} cold | fit (s) | recommend (s) |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for r in results:
        warm, cold = r.get("warm_users", {}), r.get("cold_users", {})
        cell = lambda d, m: _fmt(d[f"{m}@{k}"]) if d else "n/a"  # noqa: E731
        lines.append(
            f"| {r['label']} | {cell(warm, 'ndcg')} | {cell(warm, 'recall')} | {cell(cold, 'ndcg')} | "
            f"{cell(cold, 'recall')} | {r['fit_seconds']:.1f} | {r['recommend_seconds']:.1f} |"
        )
    return "\n".join(lines) + "\n"


def write_results_table(results_dir: Path, out_path: Path, k_values: list[int]) -> Path:
    out_path.write_text(render_table(load_results(results_dir), k_values), encoding="utf-8")
    return out_path
