"""Descriptive statistics for the processed dataset, written as JSON and Markdown.

All numbers in the report are computed from the processed Parquet files; the
Markdown file is generated, never edited by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd


def _quantiles(counts: pd.Series) -> dict[str, float]:
    q = counts.quantile([0.5, 0.9, 0.99])
    return {
        "min": int(counts.min()),
        "median": float(q.loc[0.5]),
        "p90": float(q.loc[0.9]),
        "p99": float(q.loc[0.99]),
        "max": int(counts.max()),
        "mean": round(float(counts.mean()), 3),
    }


def _iso(ms: int) -> str:
    return pd.Timestamp(ms, unit="ms", tz="UTC").isoformat()


def platform_of(categories: Any) -> str | None:
    """The second category level is the platform ("PC", "PlayStation 4", ...)."""
    if categories is None or len(categories) < 2:
        return None
    return str(categories[1])


def compute_stats(interactions: pd.DataFrame, products: pd.DataFrame, top_n: int = 10) -> dict[str, Any]:
    n_users = interactions["user_id"].nunique()
    n_items = interactions["item_id"].nunique()
    n_inter = len(interactions)

    per_user = interactions.groupby("user_id").size()
    per_item = interactions.groupby("item_id").size()
    years = pd.to_datetime(interactions["timestamp"], unit="ms", utc=True).dt.year

    platforms = products["categories"].map(platform_of).dropna()

    def coverage(col: str) -> float:
        s = products[col]
        if s.dtype == object:
            present = s.map(lambda v: v is not None and (len(v) > 0 if hasattr(v, "__len__") else True))
        else:
            present = s.notna()
        return round(float(present.mean()), 4)

    return {
        "interactions": n_inter,
        "users": n_users,
        "items": n_items,
        "density": round(n_inter / (n_users * n_items), 6),
        "time_range": {
            "first": _iso(int(interactions["timestamp"].min())),
            "last": _iso(int(interactions["timestamp"].max())),
        },
        "interactions_per_user": _quantiles(per_user),
        "interactions_per_item": _quantiles(per_item),
        "users_below_5_interactions": int((per_user < 5).sum()),
        "items_below_5_interactions": int((per_item < 5).sum()),
        "rating_distribution": {
            str(int(k)): int(v) for k, v in interactions["rating"].value_counts().sort_index().items()
        },
        "interactions_per_year": {str(k): int(v) for k, v in years.value_counts().sort_index().items()},
        "metadata_coverage": {
            col: coverage(col)
            for col in ["description", "features", "brand", "price", "image_url", "date_first_available"]
            if col in products
        },
        "top_platforms": {str(k): int(v) for k, v in platforms.value_counts().head(top_n).items()},
        "top_brands": {
            str(k): int(v) for k, v in products["brand"].dropna().value_counts().head(top_n).items()
        },
    }


def _table(mapping: dict[str, Any], key: str, value: str) -> str:
    lines = [f"| {key} | {value} |", "|---|---|"]
    lines += [f"| {k} | {v:,} |" if isinstance(v, int) else f"| {k} | {v} |" for k, v in mapping.items()]
    return "\n".join(lines)


def render_markdown(stats: dict[str, Any], clean_report: dict[str, int], category: str) -> str:
    headline = {
        "Interactions": stats["interactions"],
        "Users": stats["users"],
        "Items": stats["items"],
        "Density": stats["density"],
        "First interaction": stats["time_range"]["first"],
        "Last interaction": stats["time_range"]["last"],
    }
    parts = [
        f"# Dataset report: {category} (5-core)",
        "_Generated by `python -m cartsense_ml.data.pipeline`. Do not edit by hand._",
        "## Overview",
        _table(headline, "Metric", "Value"),
        "## Cleaning",
        _table(clean_report, "Step", "Rows"),
        "## Activity distribution",
        _table(stats["interactions_per_user"], "Interactions per user", "Value"),
        _table(stats["interactions_per_item"], "Interactions per item", "Value"),
        f"Users with fewer than 5 interactions after cleaning: {stats['users_below_5_interactions']:,}; "
        f"items: {stats['items_below_5_interactions']:,}.",
        "## Ratings",
        _table(stats["rating_distribution"], "Rating", "Count"),
        "## Interactions per year",
        _table(stats["interactions_per_year"], "Year", "Count"),
        "## Metadata coverage (share of products with the field)",
        _table(stats["metadata_coverage"], "Field", "Coverage"),
        "## Top platforms",
        _table(stats["top_platforms"], "Platform", "Products"),
        "## Top brands",
        _table(stats["top_brands"], "Brand", "Products"),
    ]
    return "\n\n".join(parts) + "\n"


def write_report(
    stats: dict[str, Any], clean_report: dict[str, int], category: str, reports_dir: Path
) -> tuple[Path, Path]:
    reports_dir.mkdir(parents=True, exist_ok=True)
    json_path = reports_dir / "data_stats.json"
    md_path = reports_dir / "data_stats.md"
    json_path.write_text(
        json.dumps({"clean": clean_report, "stats": stats}, indent=2) + "\n", encoding="utf-8"
    )
    md_path.write_text(render_markdown(stats, clean_report, category), encoding="utf-8")
    return json_path, md_path
